/**
 * A folder of the whole app, small enough to hand to someone else (or to
 * another AI) to read.
 *
 *   node scripts/bundle-for-review.mjs            → ../founderfloor-review/
 *   node scripts/bundle-for-review.mjs --out DIR  → somewhere else
 *   node scripts/bundle-for-review.mjs --zip      → also makes the .zip
 *
 * What goes in: every file git is tracking that a reader can read. Taking
 * the list from git is the safety rule, not a convenience — anything
 * ignored (node_modules, .env, the native iOS and Android projects, build
 * output, the floor server's data file) cannot be in the list, so a secret
 * cannot ride along by accident.
 *
 * What stays out, and why: pictures, fonts, video and spreadsheets (a
 * reader cannot read them and they are most of the weight), the lock
 * files (noise), and .claude/skills (third-party tooling that is not this
 * app). Everything left out is still listed in MANIFEST.txt by name, so
 * the reader knows what exists.
 *
 * A READ-ME-FIRST.md is written at the top of the folder: what the
 * product is, who it is for, how the code is laid out, what is finished
 * and what is not.
 */
import { execFileSync } from "node:child_process";
import { cpSync, mkdirSync, rmSync, writeFileSync, existsSync, statSync } from "node:fs";
import { dirname, join, resolve } from "node:path";

const ROOT = resolve(import.meta.dirname, "..");
const args = process.argv.slice(2);
const outArg = args.indexOf("--out");
const OUT = resolve(outArg >= 0 ? args[outArg + 1] : join(ROOT, "..", "founderfloor-review"));
const ZIP = args.includes("--zip");

/** Files a person cannot read in a text editor, plus noise with no review value. */
const SKIP_EXT = /\.(png|jpe?g|gif|webp|ico|svg|ttf|otf|woff2?|mp4|webm|mov|mp3|wav|xlsx|xls|pdf|zip|pyc)$/i;
const SKIP_PATH = [
  /^\.claude\/skills\//, // third-party tooling, not this app
  /^\.claude\/agents\//,
  /package-lock\.json$/,
  /^tools\/.*\.py$/, // one-off art scripts
];

const tracked = execFileSync("git", ["ls-files"], { cwd: ROOT, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 })
  .split("\n")
  .filter(Boolean);

const keep = [];
const left = [];
for (const f of tracked) {
  if (SKIP_EXT.test(f) || SKIP_PATH.some((r) => r.test(f))) left.push(f);
  else keep.push(f);
}

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
let bytes = 0;
for (const f of keep) {
  const from = join(ROOT, f);
  if (!existsSync(from)) continue;
  const to = join(OUT, f);
  mkdirSync(dirname(to), { recursive: true });
  cpSync(from, to);
  bytes += statSync(from).size;
}

const commit = execFileSync("git", ["log", "-1", "--format=%h %s"], { cwd: ROOT, encoding: "utf8" }).trim();
const branch = execFileSync("git", ["rev-parse", "--abbrev-ref", "HEAD"], { cwd: ROOT, encoding: "utf8" }).trim();
const when = execFileSync("git", ["log", "-1", "--format=%cs"], { cwd: ROOT, encoding: "utf8" }).trim();

/** The left-out list, grouped by folder, so the reader knows what exists without carrying it. */
const byFolder = new Map();
for (const f of left) {
  const k = f.split("/").slice(0, 2).join("/");
  byFolder.set(k, (byFolder.get(k) ?? 0) + 1);
}
writeFileSync(
  join(OUT, "MANIFEST.txt"),
  [
    `FounderFloor, files in this folder`,
    `branch ${branch}, commit ${commit}, ${when}`,
    `${keep.length} files, ${(bytes / 1024 / 1024).toFixed(1)} MB`,
    ``,
    `IN THIS FOLDER`,
    ...keep.map((f) => `  ${f}`),
    ``,
    `NOT IN THIS FOLDER (${left.length} files: pictures, fonts, video, spreadsheets, lock files, third-party tooling)`,
    ...[...byFolder.entries()].sort((a, b) => b[1] - a[1]).map(([k, n]) => `  ${k}  ${n} files`),
    ``,
    `Also absent because git never tracked them: node_modules, build output,`,
    `the native iOS and Android projects (generated by expo prebuild), the`,
    `floor server's data file, and every .env. No key or password is in here.`,
    ``,
  ].join("\n"),
);

writeFileSync(join(OUT, "READ-ME-FIRST.md"), readme({ branch, commit, when, files: keep.length, mb: (bytes / 1024 / 1024).toFixed(1) }));

console.log(`${OUT}`);
console.log(`${keep.length} files, ${(bytes / 1024 / 1024).toFixed(1)} MB (${left.length} binary or third-party files left out)`);

if (ZIP) {
  const zip = `${OUT}.zip`;
  rmSync(zip, { force: true });
  execFileSync("zip", ["-qr", zip, OUT.split("/").pop()], { cwd: dirname(OUT) });
  console.log(`${zip}  ${(statSync(zip).size / 1024 / 1024).toFixed(1)} MB`);
}

function readme({ branch, commit, when, files, mb }) {
  return `# FounderFloor, for review

This is the whole of an app called FounderFloor, as source, for someone (or
some model) to read and pick holes in. ${files} files, ${mb} MB, from branch
\`${branch}\`, commit \`${commit}\`, ${when}.

## What it is

An iPhone app that takes one person from a start-up idea to a start-up with a
paying customer. The person it is built for has never built a company or an
app, does not know the words, and works evenings alone on a phone beside a job.

It is drawn as a permanent trade-show hall. A building with six rooms (idea,
validate, set up, first customers, money, raise), a reception desk and four
coaches, all pixel-art characters called keepers. The founder walks a road of
seven stops: say your idea, make your plan, ask five people, do this week, see
your app, build it, first paying customer. Every stop is on the Today tab with
the one thing to do next.

The rhythm is weekly, never daily: a Monday plan, three tasks a week, a Friday
log of five numbers, and the week read back with a score out of 100.

## The five rules it is built to

1. One thing to do next, always visible, in words a child follows.
2. The building does the building. The founder talks to people, decides, and
   writes down what happened; the app writes the plan, the task pages, the app
   mock-up and the build brief.
3. Nothing written is lost. Every line the founder writes is kept and shapes
   the plan, the tasks, the mock-up and the brief from then on.
4. Honest state. Practice mode says it is practice, samples say they are
   samples, and no number is invented.
5. Real people and real money beat likes, features and polish.

## How it is laid out

| Where | What |
|---|---|
| \`apps/mobile\` | The product. Expo SDK 57, React Native, Expo Router. Screens in \`src/app\`, logic in \`src/lib\`. |
| \`packages/shared\` | Every rule, prompt and pure function, with the tests. Read this first. |
| \`packages/ui\` | The design system: tokens, theme, and every component, including the pixel-art building. |
| \`app\`, \`components\`, \`lib\`, \`game\` | A Next.js website at the repo root: public stand pages and the walkable hall. Secondary. |
| \`server\` | A small Node floor server for the hall and accounts. |
| \`supabase\` | Edge functions that hold the Anthropic key and answer the app. |
| \`docs\` | Design and product documents, including the user research the recent work came from. |

Worth reading in this order: \`PRODUCT.md\` (what is true about the product),
\`DESIGN.md\` (the visual contract and the list of things that must never come
back), \`docs/research/what-people-want.md\` (537 sources on what makes people
keep or delete an app, which drives the current work), then
\`packages/shared/src\`, then \`apps/mobile/src/app\`.

## Two running modes, and what Pro buys

On Free the building writes every plan, task page, brief and reply itself from
the founder's own words, whole, labelled as practice. Pro turns the staff on:
the desk and the four coaches answer live through a model and FounderFloor
pays for the words. A founder who already has an Anthropic key can put it in
Settings; that changes who pays, not what the plan allows. Nothing asks for a
key before the founder has said their idea.

## What is finished and what is not

Finished: the road and the seven stops, the six rooms and the plan, task pages
with steps, the small rooms where the founder writes what happened, the
notebook, the Workshop (it draws the founder's app as tappable screens and
writes a build brief for Lovable, Bolt, v0, Base44 or Claude Code), the Friday
log and the week read back, the pixel building on the map, the whole practice
mode, and a copy of everything the founder can take out and put back.

The most recent work is all in the Workshop's studio. Three things worth
knowing before reading it. Pictures are asked for by subject, not by shape:
\`studio/scenes.ts\` holds seventeen drawings and the product's own noun picks
one, so a bakery shows bread rather than brown rectangles. The first take is
drawn to the platform's own chassis — a near-neutral ground, content in boxed
groups, the brand on the controls rather than the page, the system type at the
system's sizes — with the product's own palette and category layout on top; the
market's own looks are a seed away. And the finish is deliberately technical:
hairlines instead of shadows, 10 to 12px corners, figures in a monospaced face
at tabular widths, captions as small letterspaced capitals, states as outlined
tags. \`handoff.ts\` hands all of that to a builder tool in the form it writes
files in, so what comes back out of Lovable is the app the founder was looking
at rather than a different one with the same words.

Not finished, and known: billing is not wired (purchases are a sandbox
stub, RevenueCat is planned), the floor of other founders is built but shut
behind a coming-soon page until there are founders on it, Android has not been
started, and there is no analytics of any kind. There are no users yet, no
revenue and no testimonials; anything in the app that looks like a customer is
a labelled sample, and that labelling is deliberate.

## What would be most useful to have checked

- Correctness and edge cases in \`packages/shared/src\`, especially \`weeks.ts\`
  (the plan's weeks advance by weeks worked, not by the calendar),
  \`review.ts\` (the week's score) and \`tasks.ts\`.
- Whether the state in \`apps/mobile/src/lib/store.ts\` can lose a founder's
  writing under any sequence of events. Losing what someone wrote is the one
  unforgivable bug here.
- Whether practice mode is genuinely complete: no screen empty or broken
  because no model answered.
- Whether the app ever punishes an absence. It is supposed to be impossible:
  no streak that resets, no number that falls to zero, no score lowered by
  time away.
- Whether the interface reads as machine-generated. That is the standing
  worry; \`DESIGN.md\` lists the tells that have already been removed.
- Whether the generated mock-ups in \`packages/shared/src/studio\` look like
  software or like a website made narrow. \`scripts/measure-mockups.mjs\` opens
  every screen of nine sample products in a browser and checks the things the
  eye is bad at — columns meant to be equal, a number centred in its ring,
  nothing off the screen or under 44px to press — and passes; what it cannot
  check is whether the result has any taste.
- Accessibility: labels, roles, 44pt targets, Dynamic Type, and both
  appearances.

## What is not in this folder

Pictures, fonts, video and spreadsheets are left out because a reader cannot
read them and they are most of the weight; \`MANIFEST.txt\` lists what exists.
The pixel art is real and is referenced from \`packages/ui/src/atlas.gen.ts\`.
Also absent, because git never tracked them: node_modules, build output, the
native iOS and Android projects, and every .env file. There is no key,
password or personal data in here.

## Running it, if you want to

\`\`\`
npm install
cd apps/mobile && npm install && npx expo start
\`\`\`

The app runs fully offline in practice mode with no key and no account.
\`cd packages/shared && npm test\` runs the test suite.
`;
}
